#!/usr/bin/env python3
"""Fetch a vault key's public PEM from the running Zsign API and write
both the PEM and an MCUboot Kconfig fragment that embeds it as the
bootloader's trust anchor.

This is the bootloader-provisioning half of spec.md's two independent
workflows (agent exports public PEM -> MCUboot embeds verification
key -> provision bootloader), kept separate from application signing.
Run it once per key, before building MCUboot -- not per DFU cycle.

Token comes from ZSIGN_API_TOKEN (not a CLI flag), same convention as
dfu_demo.py and spec.md's own sign_with_agent.py example.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import httpx

DEFAULT_API_URL = "http://127.0.0.1:8765"
DEFAULT_OUT_DIR = Path(__file__).resolve().parent.parent / "keys"

CONF_HEADER = (
    "# Autogenerated by fetch_public_key.py -- do not edit by hand, rerun\n"
    "# the script instead (e.g. after rotating the key). Confirm symbol\n"
    "# names and crypto backend support match your pinned MCUboot tree\n"
    "# before trusting this for anything beyond this demo.\n"
)

# MCUboot's Zephyr port (boot/zephyr/Kconfig) only ships verification
# for these three signature types -- no P-384, even though imgtool can
# generate P-384 keys. Matches zsign.vault.crypto's own algorithm set.
SIGNATURE_TYPE_CONF = {
    "ecdsa-p256": "CONFIG_BOOT_SIGNATURE_TYPE_ECDSA_P256=y\n",
    "ed25519": "CONFIG_BOOT_SIGNATURE_TYPE_ED25519=y\n",
    "rsa-2048": "CONFIG_BOOT_SIGNATURE_TYPE_RSA=y\nCONFIG_BOOT_SIGNATURE_TYPE_RSA_LEN=2048\n",
    "rsa-3072": "CONFIG_BOOT_SIGNATURE_TYPE_RSA=y\nCONFIG_BOOT_SIGNATURE_TYPE_RSA_LEN=3072\n",
}


def fail(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    sys.exit(1)


def discover_key(api_url: str, token: str, explicit_key_id: str | None) -> dict:
    response = httpx.get(f"{api_url}/v1/keys", headers={"Authorization": f"Bearer {token}"})
    if response.status_code != 200:
        fail(f"GET /v1/keys failed: HTTP {response.status_code}: {response.text}")
    keys = response.json()
    if explicit_key_id:
        for key in keys:
            if key["key_id"] == explicit_key_id:
                return key
        fail(f"key_id {explicit_key_id} not visible to this token")
    active = [k for k in keys if k["lifecycle_state"] == "active"]
    if not active:
        fail("no active keys visible to this token's project")
    if len(active) > 1:
        options = ", ".join(f"{k['label']} ({k['key_id']})" for k in active)
        fail(f"multiple active keys available, pass --key-id explicitly: {options}")
    return active[0]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--api-url", default=DEFAULT_API_URL)
    parser.add_argument("--key-id", default=None,
                         help="Explicit vault key id (default: auto-discover the one active key)")
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()

    token = os.environ.get("ZSIGN_API_TOKEN")
    if not token:
        fail("ZSIGN_API_TOKEN is not set (issue a sign-scoped token from the GUI)")

    key = discover_key(args.api_url, token, args.key_id)
    pem_response = httpx.get(
        f"{args.api_url}/v1/keys/{key['key_id']}/public.pem",
        headers={"Authorization": f"Bearer {token}"},
    )
    if pem_response.status_code != 200:
        fail(f"GET public.pem failed: HTTP {pem_response.status_code}: {pem_response.text}")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    pem_path = args.out_dir / f"{key['label']}-public.pem"
    pem_path.write_bytes(pem_response.content)

    algorithm = key["algorithm"]
    if algorithm not in SIGNATURE_TYPE_CONF:
        fail(
            f"no MCUboot Kconfig mapping for algorithm {algorithm!r}; supported: "
            f"{sorted(SIGNATURE_TYPE_CONF)}"
        )

    conf_path = args.out_dir / "mcuboot-public-key.conf"
    conf_path.write_text(
        CONF_HEADER
        + SIGNATURE_TYPE_CONF[algorithm]
        + f'CONFIG_BOOT_SIGNATURE_KEY_FILE="{pem_path.resolve()}"\n'
        + "\n"
        + "# This demo always overwrites the primary slot directly\n"
        + "# (direct-flash via programmer, no secondary slot/OTA transport)\n"
        + "# -- overwrite-only is the correct bootloader mode for that. The\n"
        + "# newer default \"swap using offset\" mode expects an actual\n"
        + "# secondary-slot upgrade and fails to validate a primary-only\n"
        + "# image (confirmed on real hardware: boot_check_header_valid\n"
        + "# failed, MCUboot scrambled the slot on the first failed boot).\n"
        + "CONFIG_BOOT_UPGRADE_ONLY=y\n"
    )

    print(f"key:    {key['label']} ({key['key_id']}), project={key['project']}")
    print(f"pem:    {pem_path}")
    print(f"conf:   {conf_path}")
    print()
    print("Build MCUboot with this fragment, then flash it once:")
    print(
        f"  west build -b <board> -d <mcuboot_build_dir> "
        f"external/bootloader/mcuboot/boot/zephyr --pristine \\\n"
        f"    -- -DEXTRA_CONF_FILE={conf_path.resolve()}\n"
        f"  west flash -d <mcuboot_build_dir>"
    )


if __name__ == "__main__":
    main()
